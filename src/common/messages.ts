const dict: Record<Lang, Record<string, string>> = { en, ar, ur };

export function t(key: string, lang: Lang = 'en', params?: Record<string, any>): string {
  let s = dict[lang]?.[key] ?? dict.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v ?? ''));
  return s;
}

/** Logged-in user's saved preference wins; otherwise the Accept-Language header; default English. */
export function resolveLang(req: any): Lang {
  const userLang = req?.user?.language;
  if (isLang(userLang)) return userLang;
  const header = String(req?.headers?.['accept-language'] || '').toLowerCase();
  if (header.startsWith('ar')) return 'ar';
  if (header.startsWith('ur')) return 'ur';
  return 'en';
}
