import 'dotenv/config';
import mongoose from 'mongoose';
const B = 'https://lms-backend-poc.onrender.com/api';
const ok = (n, c, g = '') => console.log(`${c ? 'PASS' : 'FAIL'}  ${n}  ${g}`);
await mongoose.connect(process.env.MONGO_URI);
const files = mongoose.connection.db.collection('uploads.files');
const tok = (await (await fetch(B + '/auth/verify-otp', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ phone: '0500000036', otp: '123456' }) })).json()).data.token;
const png = Buffer.from('89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c4890000000d49444154789c63000100000500010d0a2db40000000049454e44ae426082', 'hex');
const fd = new FormData(); fd.append('file', new Blob([png], { type: 'image/png' }), 'test.png');
const up = await (await fetch(B + '/users/me/avatar', { method: 'POST', headers: { Authorization: 'Bearer ' + tok }, body: fd })).json();
const url = up.data?.avatarUrl; const p = url && new URL(url).pathname;
ok('Rider upload', !!url, url);
ok('Saved in Atlas GridFS', (await files.countDocuments({ filename: p })) === 1, p);
const g = await fetch(url); ok('Loads on live', g.status === 200 && Buffer.from(await g.arrayBuffer()).equals(png), `${g.status} ${g.headers.get('content-type')}`);
const del = await (await fetch(B + '/users/me/avatar', { method: 'DELETE', headers: { Authorization: 'Bearer ' + tok } })).json();
ok('Delete: avatarUrl null', del.data?.avatarUrl === null);
ok('Delete: removed from Atlas', (await files.countDocuments({ filename: p })) === 0);
ok('Delete: live 404', (await fetch(url, { method: 'HEAD' })).status === 404);
await mongoose.disconnect();
